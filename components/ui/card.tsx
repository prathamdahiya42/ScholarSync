import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "glow-card rounded-[var(--radius-md)] border border-[var(--border)] bg-[var(--card)] p-4 md:p-5 shadow-[var(--shadow-sm)] text-[var(--foreground)]",
      hoverable &&
        "transition-colors duration-180 hover:border-[var(--border-strong)] hover:shadow-[var(--shadow-md)]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

